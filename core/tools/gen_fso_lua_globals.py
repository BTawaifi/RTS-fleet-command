"""Generate the FSO scripting-global allowlist from the engine source.

The engine source is the only authority for what mission Lua can read. Hand-
typing the list is exactly how `ai-fly-to` (an SEXP that does not exist) got
into a release, so the allowlist for the scope checker is EXTRACTED rather than
remembered.

Emits a Python module of sorted name sets:

  * ORDER_/MOUSE_/FLIGHTMODE_/SEXPVAR_/... enum constants, from
    code/scripting/api/objs/enums.cpp  (the lua_enum_def_list)
  * every scripting namespace (mn, gr, hud, ship, ...)
    and every bare global, from the luaL_register calls in
    code/scripting/api/libs/*.cpp and code/scripting/scripting.cpp

Run:  python core/tools/gen_fso_lua_globals.py
Writes core/tools/fso_lua_globals_generated.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ENGINE = Path(r"D:\Games\FreespaceOpen\src\fs2open\code")
OUT = TOOLS / "fso_lua_globals_generated.py"

ENUM_CPP = ENGINE / "scripting" / "api" / "objs" / "enums.cpp"

# {"NAME", LE_VALUE, true} inside the lua_enum_def_list
ENUM_ROW = re.compile(r'\{\s*"([A-Z][A-Z0-9_]*)"\s*,')

# ADE_LIB(l_Base, "Base", "ba", "desc")  ->  the `ba` namespace is a Lua global.
# The third field is the SHORT name, which is what mission Lua actually types;
# ADE_LIB_DERIV(..., NULL, ...) registers only a nested table under its parent.
ADE_LIB = re.compile(r'ADE_LIB\(\s*\w+\s*,\s*"[^"]*"\s*,\s*"([A-Za-z_][\w]*)"')
ADE_LIB_ANY = re.compile(r'ADE_LIB(?:_DERIV)?\(\s*\w+\s*,\s*"[^"]*"\s*,\s*'
                         r'(NULL|"([A-Za-z_][\w]*)")')

# ADE_OBJ_DERIV(l_Ship, object_h, "ship", "desc", l_Object) -> `ship` is a Lua
# global constructor. This is where `pc`, `vec`, `gr`, `mn.Lua`'s receiver and
# every other engine object class comes from.
ADE_OBJ = re.compile(r'ADE_OBJ(?:_DERIV|_VALIDATOR|_NO_MULTI)?\(\s*\w+\s*,'
                     r'\s*[\w:<>\s*]+?\s*,\s*"([A-Za-z_][\w]*)"')

# Bare globals the engine sets directly, e.g. screen/game time globals.
SET_GLOBAL = re.compile(r'lua_setglobal\s*\(\s*\w+\s*,\s*"([^"]+)"')
PUSH_GLOBAL = re.compile(r'lua_push\w*\s*\([^;]*?;\s*lua_setglobal\s*\(\s*\w+\s*,\s*"([^"]+)"',
                         re.S)


def collect_enums() -> set[str]:
    if not ENUM_CPP.exists():
        raise SystemExit(f"engine source not found: {ENUM_CPP}")
    text = ENUM_CPP.read_text(encoding="utf-8", errors="replace")
    head = text.split("};", 1)[0]          # the enum table ends at the first };
    return set(ENUM_ROW.findall(head))


def _source_files() -> list[Path]:
    roots = [ENGINE / "scripting", ENGINE / "hud", ENGINE / "mission",
             ENGINE / "playerman", ENGINE / "object"]
    files: list[Path] = []
    for root in roots:
        if root.exists():
            files.extend(root.rglob("*.cpp"))
            files.extend(root.rglob("*.h"))
    return sorted(set(files))


def collect_registrations() -> set[str]:
    """Namespaces (`ba`, `gr`, `mn`, ...) the engine binds as Lua globals.

    Only the SHORT name from ADE_LIB is a global: `ADE_LIB(l_Base, "Base",
    "ba", ...)` makes `ba` reachable, while the derived libraries pass NULL
    and register a nested table under an existing parent instead."""
    names: set[str] = set()
    for path in _source_files():
        text = path.read_text(encoding="utf-8", errors="replace")
        # a macro inside a comment is not a registration
        text = re.sub(r"//[^\n]*", " ", text)
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        for m in ADE_LIB.finditer(text):
            names.add(m.group(1))
        for m in ADE_OBJ.finditer(text):
            names.add(m.group(1))
        for m in SET_GLOBAL.finditer(text):
            names.add(m.group(1))
        for m in PUSH_GLOBAL.finditer(text):
            names.add(m.group(1))
    return {n for n in names if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n)}


HEADER = r'''"""AUTO-GENERATED by tools/gen_fso_lua_globals.py -- do not edit by hand.

Extracted from the engine source so the scope-order checker's allowlist can
never drift from what FSO actually registers with Lua. Regenerate after an
engine update:

    python core/tools/gen_fso_lua_globals.py

Sources scanned:
  {enum_src}
  code/scripting/**, code/hud/**, code/mission/**, code/object/**, code/playerman/**

A row in enums.cpp carries a trailing `true` when the engine also pushes the
enum as a bare Lua global, which is why ORDER_ATTACK resolves without the mod
ever declaring it. ADE_LIB's third field is the short name mission Lua types
(`ADE_LIB(l_Base, "Base", "ba", ...)` makes `ba` global); ADE_LIB_DERIV passes
NULL and registers a nested table instead. ADE_OBJ's name field is the engine
object constructor, which is where `ship`, `pc`, `vector`, `team` come from.
"""

# Enum constants the engine pushes as bare mission-Lua globals.
# ORDER_ATTACK, MOUSE_LEFT_BUTTON, FLIGHTMODE_SHIPLOCKED, SEXPVAR_*, ...
FSO_ENUM_GLOBALS = frozenset({enums!r})

# Namespaces and functions the engine binds directly (ba, gr, mn, ship, ...).
FSO_REGISTERED_GLOBALS = frozenset({registered!r})

FSO_LUA_GLOBALS = FSO_ENUM_GLOBALS | FSO_REGISTERED_GLOBALS
'''


def main() -> int:
    enums = collect_enums()
    registered = collect_registrations()
    if not enums:
        raise SystemExit("no enums extracted; the enums.cpp pattern is stale")
    OUT.write_text(HEADER.format(
        enums=sorted(enums),
        registered=sorted(registered),
        enum_src=str(ENUM_CPP),
    ), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(enums)} enum globals, "
          f"{len(registered)} registered names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
